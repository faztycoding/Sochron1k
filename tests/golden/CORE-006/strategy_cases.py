from datetime import datetime, timedelta


def _clock(start, count, skip=()):
    """`count` M15 open times from `start` (UTC), leaving out the times in `skip`."""
    first = datetime.fromisoformat(start)
    stamps = []
    step = 0
    while len(stamps) < count:
        stamp = (first + timedelta(minutes=15 * step)).isoformat(timespec="minutes")
        step += 1
        if stamp not in skip:
            stamps.append(stamp)
    return tuple(stamps)


